    function addItemGalleryWorksRequest() {
        let formData = new FormData($('#addItemGalleryWorks')[0])

        $.ajax({
            url: '/admin/request/galleryWorks/addItemCatalogSave.php',
            method: 'post',
            cache: false,
            contentType: false,
            processData: false,
            data: formData,
            success: function (data) {
                var response = data;

                if (typeof data === 'string') {
                    var trimmed = data.trim();

                    if (trimmed === 'success') {
                        response = {status: 'success'};
                    } else if (trimmed.length) {
                        try {
                            response = JSON.parse(trimmed);
                        } catch (e) {
                            response = {status: 'error', message: trimmed};
                        }
                    } else {
                        response = {status: 'error'};
                    }
                }

                if (response && response.status === 'success') {
                    toastr.success('Работа добавлена');
                    $('#addItemGalleryWorks')[0].reset();
                    $('#ModalAddGalleryWorks').modal('hide');
                    getGalleryWorksRequest();
                    loadGalleryCategories(true);
                    return;
                }

                alert((response && response.message) ? response.message : 'Не удалось добавить работу');
            },
            error: handleAjaxError
        });
    }

